let current = 'es';

export function setLang(l) { current = LANGS.includes(l) ? l : 'es'; document.documentElement.lang = current; }
export function lang() { return current; }
export function t(key) { return S[current][key] ?? S.es[key]; }
// Pick a localized value from a data field that may be a plain string or {es,en,eu}.
export function L(v) { return v == null ? '' : (typeof v === 'string' ? v : (v[current] ?? v.es)); }

export function detectLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(q)) return q;
  const nav = (navigator.language || 'es').slice(0, 2);
  return LANGS.includes(nav) ? nav : 'es';
}
